"""Writes ../keymap.json. macOS virtual keycodes are the wire; Windows scancodes are set 1 make codes."""
import json, os

# name: (macOS keycode, Windows scancode, extended)
KEYS = {}
def k(name, mac, sc, ext=False): KEYS[name] = (mac, sc, ext)

letters = "a s d f h g z x c v - b q w e r y t".split()
mac_letters = {"a":0,"s":1,"d":2,"f":3,"h":4,"g":5,"z":6,"x":7,"c":8,"v":9,"b":11,"q":12,"w":13,"e":14,"r":15,"y":16,"t":17,
               "o":31,"u":32,"i":34,"p":35,"l":37,"j":38,"k":40,"n":45,"m":46}
win_letters = {"q":0x10,"w":0x11,"e":0x12,"r":0x13,"t":0x14,"y":0x15,"u":0x16,"i":0x17,"o":0x18,"p":0x19,"a":0x1E,"s":0x1F,
               "d":0x20,"f":0x21,"g":0x22,"h":0x23,"j":0x24,"k":0x25,"l":0x26,"z":0x2C,"x":0x2D,"c":0x2E,"v":0x2F,"b":0x30,
               "n":0x31,"m":0x32}
mac_letters["u"]=32
for c in win_letters: k(c, mac_letters[c], win_letters[c])
mac_digits = {"1":18,"2":19,"3":20,"4":21,"5":23,"6":22,"7":26,"8":28,"9":25,"0":29}
for i, d in enumerate("1234567890"): k(d, mac_digits[d], 0x02 + i)
for name, mac, sc in [("minus",27,0x0C),("equal",24,0x0D),("leftBracket",33,0x1A),("rightBracket",30,0x1B),
                      ("backslash",42,0x2B),("semicolon",41,0x27),("quote",39,0x28),("grave",50,0x29),
                      ("comma",43,0x33),("period",47,0x34),("slash",44,0x35),("space",49,0x39),
                      ("return",36,0x1C),("tab",48,0x0F),("backspace",51,0x0E),("escape",53,0x01)]:
    k(name, mac, sc)
for i, mac in enumerate([122,120,99,118,96,97,98,100,101,109]): k(f"f{i+1}", mac, 0x3B + i)
k("f11", 103, 0x57); k("f12", 111, 0x58)
for name, mac, sc in [("home",115,0x47),("up",126,0x48),("pageUp",116,0x49),("left",123,0x4B),("right",124,0x4D),
                      ("end",119,0x4F),("down",125,0x50),("pageDown",121,0x51),("forwardDelete",117,0x53)]:
    k(name, mac, sc, True)
for name, mac, sc in [("keypad7",89,0x47),("keypad8",91,0x48),("keypad9",92,0x49),("keypadMinus",78,0x4A),
                      ("keypad4",86,0x4B),("keypad5",87,0x4C),("keypad6",88,0x4D),("keypadPlus",69,0x4E),
                      ("keypad1",83,0x4F),("keypad2",84,0x50),("keypad3",85,0x51),("keypad0",82,0x52),
                      ("keypadDecimal",65,0x53),("keypadMultiply",67,0x37)]:
    k(name, mac, sc)
k("keypadEnter", 76, 0x1C, True); k("keypadDivide", 75, 0x35, True)
k("capsLock", 57, 0x3A)

# Modifier policy: Command acts as Ctrl so Mac shortcuts (Cmd+C) work on Windows; Control is also Ctrl; Option is Alt.
MODIFIERS = {
    "55": {"mac": "leftCommand", "windows": "leftCtrl", "scancode": 0x1D, "extended": False},
    "54": {"mac": "rightCommand", "windows": "rightCtrl", "scancode": 0x1D, "extended": True},
    "56": {"mac": "leftShift", "windows": "leftShift", "scancode": 0x2A, "extended": False},
    "60": {"mac": "rightShift", "windows": "rightShift", "scancode": 0x36, "extended": False},
    "58": {"mac": "leftOption", "windows": "leftAlt", "scancode": 0x38, "extended": False},
    "61": {"mac": "rightOption", "windows": "rightAlt", "scancode": 0x38, "extended": True},
    "59": {"mac": "leftControl", "windows": "leftCtrl", "scancode": 0x1D, "extended": False},
    "62": {"mac": "rightControl", "windows": "rightCtrl", "scancode": 0x1D, "extended": True},
}

# Android KeyEvent.KEYCODE_* values to macOS keycodes.
ANDROID = {}
for i, c in enumerate("abcdefghijklmnopqrstuvwxyz"): ANDROID[29 + i] = KEYS[c][0]
for i, d in enumerate("0123456789"): ANDROID[7 + i] = KEYS[d][0]
for code, name in [(66,"return"),(67,"backspace"),(112,"forwardDelete"),(61,"tab"),(62,"space"),(111,"escape"),
                   (19,"up"),(20,"down"),(21,"left"),(22,"right"),(122,"home"),(123,"end"),(92,"pageUp"),(93,"pageDown"),
                   (55,"comma"),(56,"period"),(69,"minus"),(70,"equal"),(71,"leftBracket"),(72,"rightBracket"),
                   (73,"backslash"),(74,"semicolon"),(75,"quote"),(76,"slash"),(68,"grave"),(115,"capsLock")]:
    ANDROID[code] = KEYS[name][0]
for i in range(12): ANDROID[131 + i] = KEYS[f"f{i+1}"][0]
ANDROID.update({59:56, 60:60, 113:59, 114:62, 57:58, 58:61, 117:55, 118:54})

out = {
    "note": "Generated by tools/gen_keymap.py. mac is the wire keycode; scancode is a set 1 make code; extended means an E0 prefix.",
    "windowsKeyCode": 256,
    "keys": {n: {"mac": m, "scancode": s, "extended": e} for n, (m, s, e) in sorted(KEYS.items())},
    "modifiers": MODIFIERS,
    "modifierBits": {"shift": 17, "control": 18, "option": 19, "command": 20, "topRowAction": 8},
    "android": {str(a): m for a, m in sorted(ANDROID.items())},
}
path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "keymap.json")
with open(path, "w") as f:
    json.dump(out, f, indent=1)
    f.write("\n")
